// Writes the `@calimero-network/mero-js/runtime` entry points.
//
// They re-export the runtime's names from the package's own bundles
// (`index.mjs`, `index.browser.mjs`, `index.cjs`) rather than bundling the
// runtime a second time: a second copy would give `CalimeroError`,
// `ConfirmRequired`, ... a second identity, and an error thrown by
// `CalimeroClient` would not be an `instanceof` the class imported from
// `/runtime`. The names are the value exports of `src/runtime/index.ts`
// (tsc's `dist/runtime/index.js`); each must also be a root export.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const dist = fileURLToPath(new URL('../dist/', import.meta.url));
const runtime = await import(pathToFileURL(`${dist}runtime/index.js`).href);
const names = Object.keys(runtime).sort();
const root = await import(pathToFileURL(`${dist}index.mjs`).href);
const missing = names.filter((name) => !(name in root));
if (missing.length) {
  console.error(`runtime names the package root does not export: ${missing.join(', ')}`);
  process.exit(1);
}
const banner = '// Generated by scripts/runtime-entries.mjs: the runtime, from the package bundle.\n';
const list = names.map((name) => `  ${name},`).join('\n');
writeFileSync(`${dist}runtime.mjs`, `${banner}export {\n${list}\n} from './index.mjs';\n`);
writeFileSync(`${dist}runtime.browser.mjs`, `${banner}export {\n${list}\n} from './index.browser.mjs';\n`);
writeFileSync(
  `${dist}runtime.cjs`,
  `${banner}'use strict';\nconst m = require('./index.cjs');\n${names
    .map((name) => `Object.defineProperty(exports, ${JSON.stringify(name)}, { enumerable: true, get: () => m[${JSON.stringify(name)}] });`)
    .join('\n')}\n`,
);
readFileSync(`${dist}runtime/index.d.ts`);
console.log(`runtime entry points: ${names.length} names`);
